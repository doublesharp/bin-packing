// Generate contextual TypeScript assignments from REAL binding outputs.
// Run after all binding builds: node bindings/test/saw-types.mjs
// Then: tsc --strict --noEmit --lib es2022,dom --module esnext --moduleResolution bundler <printed-path>
import { createRequire } from 'node:module';
import { writeFile, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const require = createRequire(import.meta.url);
const { strips } = require('../saw-plan-smoke.cjs');
const targets = [
  ['Native', '../node/wrapper.js', '../node/wrapper'],
  ['Combined', '../wasm/dist/nodejs/bin_packing_wasm.cjs', '../wasm/dist/nodejs/bin_packing_wasm.cjs'],
  ['TwoD', '../wasm/dist/two-d/nodejs/bin_packing_wasm.cjs', '../wasm/dist/two-d/nodejs/bin_packing_wasm.cjs'],
];
const blocks = await Promise.all(['../node/wrapper.d.ts', '../wasm/types/bin_packing_wasm.d.ts', '../wasm/types/two_d.d.ts']
  .map(async p => (await readFile(new URL(p, import.meta.url), 'utf8')).split('// Workpiece-aware saw planner, schema version 1.')[1]));
if (!blocks[0] || blocks.some(b => b !== blocks[0])) throw new Error('Saw planner declarations drifted');
let source = '// Generated by saw-types.mjs from actual runtime values.\n';
for (const [name, runtime, types] of targets) {
  const api = require(runtime);
  source += `import type { SawPlan2D as ${name}Plan, SawPlanOptions2D as ${name}Options } from '${fileURLToPath(new URL(types, import.meta.url))}';\n`;
  source += `export const ${name}InputOptions: ${name}Options = { weights: { cut: 2 }, search: { max_states: 0 } };\n`;
  const problem = { sheets: [{ name: 's', width: 23, height: 19, kerf: 0 }],
    demands: [{ name: 'p', width: 5, height: 9, quantity: 1, can_rotate: false }] };
  const solution = api.solve2d(problem, { algorithm: 'guillotine' });
  for (const [i, job] of [strips(), { problem, layouts: solution.layouts, stock_indices: [0], demand_indices: [[0]] }].entries()) {
    source += `export const ${name}${i}: ${name}Plan = ${JSON.stringify(api.plan2dSawCuts(job), null, 2)};\n`;
  }
}
const output = join(tmpdir(), 'bin-packing-saw-runtime-types.ts');
await writeFile(output, source);
console.log(output);
