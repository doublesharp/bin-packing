#!/usr/bin/env python3
"""Run disposable build commands on an explicitly configured mounted volume."""
import argparse
import fcntl
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

LOCAL = '.scratch.json'
CARGO_CONFIG = '.cargo/config.toml'


def checked_root(config):
    """Never create a replacement Scratch directory on the source volume."""
    volume = Path(config['volume'])
    root = Path(config['root'])
    if not os.path.ismount(volume):
        raise ValueError(f'Scratch volume is not mounted: {volume}')
    if not root.is_relative_to(volume) or root == volume:
        raise ValueError('Scratch directory must be inside its volume')
    if root.resolve() != root:
        raise ValueError('Scratch directory must not traverse symlinks')
    return root


def cargo_configuration(root):
    """Render the managed local Cargo configuration."""
    return ('# Generated by scripts/scratch.py setup; local to this checkout.\n'
                  '[build]\n'
                  f'target-dir = {json.dumps(str(root / "target"))}\n'
                  'rustc-wrapper = ""\n\n'
                  '[env]\n'
                  f'TMPDIR = {{ value = {json.dumps(str(root / "tmp"))}, force = true }}\n')


def select_storage(source, volume=None, directory=None):
    """Use an explicit location once, or reuse this checkout's saved location."""
    if volume is None and directory is None:
        local = source / LOCAL
        if not local.exists():
            raise ValueError('First setup requires --directory PATH or --volume PATH')
        saved = json.loads(local.read_text())
        return Path(saved['volume']), Path(saved['root'])
    base = (directory if directory is not None else volume).expanduser().resolve()
    if volume is None:
        volume = base
        while not os.path.ismount(volume):
            if volume == volume.parent:
                raise ValueError('Cannot find the build directory mount')
            volume = volume.parent
    identity = hashlib.sha256(os.fsencode(source.resolve())).hexdigest()[:12]
    return volume.expanduser().resolve(), base / 'bin-packing' / identity


def setup(source, volume, root):
    """Create local configuration without replacing user configuration."""
    source, volume, root = source.resolve(), volume.resolve(), root.resolve()
    config = {'source': str(source), 'volume': str(volume), 'root': str(root)}
    cargo = source / CARGO_CONFIG
    local = source / LOCAL
    if cargo.exists() and not local.exists():
        raise ValueError('Refusing to replace existing Cargo configuration')
    previous = json.loads(local.read_text()) if local.exists() else config
    if previous['source'] != str(source):
        raise ValueError('Existing Scratch configuration belongs to a different checkout')
    if cargo.exists() and cargo.read_text() != cargo_configuration(Path(previous['root'])):
        raise ValueError('Refusing to replace modified existing Cargo configuration')
    checked_root(config)
    if root.is_relative_to(source):
        raise ValueError('Scratch directory cannot be inside the source checkout')
    root.mkdir(parents=True, exist_ok=True)
    owner = root / 'source.json'
    if owner.exists() and json.loads(owner.read_text()) != str(source):
        raise ValueError('Scratch directory belongs to another checkout')
    owner.write_text(json.dumps(str(source)) + '\n')
    for directory in ['target', 'tmp', 'cache/npm', 'cache/pnpm', 'cache/xdg', 'cache/wasm-pack', 'cache/corepack', 'cargo-home', 'workspace']:
        (root / directory).mkdir(parents=True, exist_ok=True)
    cargo_text = cargo_configuration(root)
    cargo.parent.mkdir(exist_ok=True)
    cargo.write_text(cargo_text)
    local.write_text(json.dumps(config, indent=2) + '\n')
    print(f'Scratch storage: {root}', flush=True)


def sync_sources(source, root):
    """Copy only Git-visible sources; preserve generated outputs between runs."""
    output = subprocess.check_output(
        ['git', '-C', str(source), 'ls-files', '-z', '--cached', '--others', '--exclude-standard'])
    names = set(os.fsdecode(name) for name in output.split(b'\0') if name)
    names -= {LOCAL, CARGO_CONFIG}
    workspace = root / 'workspace'
    manifest = root / 'sources.json'
    previous = set(json.loads(manifest.read_text())) if manifest.exists() else set()
    current = set()
    for name in sorted(names):
        relative = Path(name)
        if relative.is_absolute() or '..' in relative.parts:
            raise ValueError(f'Invalid source path: {name}')
        original, destination = source / relative, workspace / relative
        if not original.exists():
            continue  # A tracked source can be deleted but not yet staged.
        if original.is_symlink():
            raise ValueError(f'Source symlinks need explicit handling: {name}')
        if not original.is_file():
            raise ValueError(f'Unsupported source entry: {name}')
        if not destination.resolve().is_relative_to(workspace):
            raise ValueError(f'Build output replaced a source parent with a symlink: {name}')
        destination.parent.mkdir(parents=True, exist_ok=True)
        if not destination.exists() or original.read_bytes() != destination.read_bytes():
            shutil.copy2(original, destination)
        else:
            shutil.copymode(original, destination)
        current.add(name)
    for name in previous - current:
        stale = workspace / name
        if not stale.resolve().is_relative_to(workspace):
            raise ValueError(f'Stale source escaped build workspace: {name}')
        if stale.is_file():
            stale.unlink()
    manifest.write_text(json.dumps(sorted(current)) + '\n')
    return workspace


def run(source, command, cwd):
    """Run one command while locking its checkout-specific build workspace."""
    source = source.resolve()
    config = json.loads((source / LOCAL).read_text())
    if config['source'] != str(source):
        raise ValueError('Scratch configuration belongs to a different checkout; run setup there')
    root = checked_root(config)
    if not (root / 'source.json').exists():
        raise ValueError('Scratch storage was cleared; rerun setup')
    with (root / 'build.lock').open('a') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        workspace = sync_sources(source, root)
        working = (workspace / cwd).resolve()
        if not working.is_relative_to(workspace):
            raise ValueError('Command directory must be inside the build workspace')
        env = dict(os.environ)
        env.update({
            'BIN_PACKING_SCRATCH_ACTIVE': '1',
            'BIN_PACKING_SOURCE': str(source),
            'CARGO_TARGET_DIR': str(root / 'target'),
            'CARGO_HOME': str(root / 'cargo-home'),
            'RUSTC_WRAPPER': '',
            'TMPDIR': str(root / 'tmp'),
            'TMP': str(root / 'tmp'),
            'TEMP': str(root / 'tmp'),
            'npm_config_cache': str(root / 'cache/npm'),
            'npm_config_store_dir': str(root / 'cache/pnpm'),
            'XDG_CACHE_HOME': str(root / 'cache/xdg'),
            'WASM_PACK_CACHE': str(root / 'cache/wasm-pack'),
            'COREPACK_HOME': str(root / 'cache/corepack'),
            'PYTHONDONTWRITEBYTECODE': '1',
        })
        print(f'Build workspace: {workspace}', flush=True)
        return subprocess.run(command, cwd=working, env=env, check=False).returncode


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest='action', required=True)
    configure = commands.add_parser('setup')
    location = configure.add_mutually_exclusive_group()
    location.add_argument('--volume', type=Path, help='Mounted build volume; saved for future commands')
    location.add_argument('--directory', type=Path, help='Build storage directory; containing mount is detected')
    execute = commands.add_parser('run')
    execute.add_argument('--cwd', default='.')
    execute.add_argument('command', nargs=argparse.REMAINDER)
    commands.add_parser('status')
    args = parser.parse_args()
    source = Path(__file__).resolve().parent.parent
    if args.action == 'setup':
        volume, root = select_storage(source, args.volume, args.directory)
        setup(source, volume, root)
        return 0
    if args.action == 'status':
        config = json.loads((source / LOCAL).read_text())
        checked_root(config)
        print(json.dumps(config, indent=2))
        return 0
    command = args.command
    if command[:1] == ['--']:
        command = command[1:]
    if not command:
        parser.error('run requires a command')
    return run(source, command, args.cwd)


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        print(f'Scratch: {error}', file=sys.stderr)
        sys.exit(1)
